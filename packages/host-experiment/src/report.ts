export interface VariantMetrics {
  variant: string;
  nodeId: string;
  /** The model this variant ran (from Variant.model). */
  model: string;
  status: "completed" | "failed";
  costUsd: number;
  /** Tokens spent (from the SDK result usage; 0 if the backend reported none).
   *  tokensIn = total input processed (fresh + cache-read + cache-creation). */
  tokensIn: number;
  tokensOut: number;
  turns: number;
  /** first-event -> done, from bus event.ts. ADVISORY (concurrency-contaminated). */
  wallMs: number;
  filesChanged: number;
  insertions: number;
  deletions: number;
  commits: number;
  /** Kept, unmerged, for inspection. */
  branch: string;
  error?: string;
}

export interface ReportOptions {
  taskGoal: string;
  /** Model id for the attribution footer. */
  modelId: string;
}

/** completed before failed; within a group, cheaper first, then fewer turns. */
function rank(a: VariantMetrics, b: VariantMetrics): number {
  if (a.status !== b.status) return a.status === "completed" ? -1 : 1;
  if (a.costUsd !== b.costUsd) return a.costUsd - b.costUsd;
  return a.turns - b.turns;
}

/** The stable comparison ordering (exported so selector.ts shares one ranking). */
export function rankVariants(metrics: VariantMetrics[]): VariantMetrics[] {
  return [...metrics].sort(rank);
}

export function renderReport(
  metrics: VariantMetrics[],
  opts: ReportOptions,
): { markdown: string; json: string } {
  const ranked = rankVariants(metrics);
  const winner = ranked.find((m) => m.status === "completed") ?? null;

  const header =
    "| variant | model | status | cost ($) | tokens (in/out) | turns | wall ms (advisory) | files | +/− | commits |\n" +
    "|---|---|---|---|---|---|---|---|---|---|";
  const rows = ranked.map(
    (m) =>
      `| ${m.variant}${m === winner ? " ⭐" : ""} | ${m.model} | ${m.status}${m.error ? ` (${m.error})` : ""} | ` +
      `${m.costUsd.toFixed(4)} | ${m.tokensIn + m.tokensOut} (${m.tokensIn}/${m.tokensOut}) | ` +
      `${m.turns} | ${m.wallMs} | ${m.filesChanged} | +${m.insertions}/−${m.deletions} | ${m.commits} |`,
  );
  const branches = ranked.map(
    (m) => `- \`${m.branch}\` (${m.variant})${m === winner ? " — ⭐ winner, promoted" : " — kept, unmerged"}`,
  );

  const markdown =
    `# Experiment report\n\n` +
    `**Task:** ${opts.taskGoal}\n\n` +
    `**Winner:** ${winner ? `⭐ ${winner.variant}` : "(none — every variant failed)"}\n\n` +
    `${header}\n${rows.join("\n")}\n\n` +
    `> wall ms is **advisory** — variants ran in parallel and contend for CPU + the API rate limit; ` +
    `cost / turns / status / diff are the clean comparators.\n\n` +
    `## Branches\n\n${branches.join("\n")}\n\n` +
    `———\nGenerated by ${opts.modelId} · task completed\n`;

  const json = JSON.stringify(
    { task: opts.taskGoal, winner: winner?.variant ?? null, variants: ranked },
    null,
    2,
  );
  return { markdown, json };
}
